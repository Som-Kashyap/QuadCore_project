import enum
from typing import List, Optional, TYPE_CHECKING
from datetime import date, datetime, timezone

from sqlalchemy import (
    String,
    Float,
    ForeignKey,
    DateTime,
    Enum,
    JSON,
    Text,
    BigInteger,
    Boolean,
    Index,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.domains.firm.models import Firm
    from app.domains.documents.models import UploadedDocument
    from app.domains.activity.models import ElectricityRecord, FuelRecord, MaterialRecord


# ==============================================================================
# ENUMS
# ==============================================================================

class ReportFormat(enum.Enum):
    PDF = "pdf"
    EXCEL = "xlsx"
    CSV = "csv"
    DOCX = "docx"


class ReportType(enum.Enum):
    COMPREHENSIVE_DECARBONIZATION = "comprehensive_decarbonization"
    EU_CBAM_SUPPLIER_SHEET = "eu_cbam_supplier_sheet"
    INTERNAL_AUDIT_SUMMARY = "internal_audit_summary"


# ==============================================================================
# MODELS
# ==============================================================================

class ReportingPeriod(Base):
    """Time boundary container (monthly/quarterly) for audit inputs and calculations."""
    __tablename__ = "reporting_periods"

    id: Mapped[int] = mapped_column(primary_key=True)
    firm_id: Mapped[int] = mapped_column(ForeignKey("firms.id", ondelete="CASCADE"), nullable=False)
    start_date: Mapped[date] = mapped_column(nullable=False)
    end_date: Mapped[date] = mapped_column(nullable=False)
    
    # Operational activity totals
    production_tonnes: Mapped[Optional[float]] = mapped_column(Float)  # Total billet produced
    
    # Deterministic output results
    total_scope1_tco2e: Mapped[Optional[float]] = mapped_column(Float)
    total_scope2_tco2e: Mapped[Optional[float]] = mapped_column(Float)
    total_precursor_tco2e: Mapped[Optional[float]] = mapped_column(Float)
    total_emissions_tco2e: Mapped[Optional[float]] = mapped_column(Float)
    specific_emissions_tco2e_per_tonne: Mapped[Optional[float]] = mapped_column(Float)
    is_calculation_stale: Mapped[bool] = mapped_column(Boolean, default=True)

    firm: Mapped["Firm"] = relationship(back_populates="reporting_periods")
    uploaded_documents: Mapped[List["UploadedDocument"]] = relationship(
        back_populates="reporting_period", cascade="all, delete-orphan"
    )
    generated_reports: Mapped[List["GeneratedReport"]] = relationship(
        back_populates="reporting_period", cascade="all, delete-orphan"
    )
    
    electricity_records: Mapped[List["ElectricityRecord"]] = relationship(
        back_populates="reporting_period", cascade="all, delete-orphan"
    )
    fuel_records: Mapped[List["FuelRecord"]] = relationship(
        back_populates="reporting_period", cascade="all, delete-orphan"
    )
    material_records: Mapped[List["MaterialRecord"]] = relationship(
        back_populates="reporting_period", cascade="all, delete-orphan"
    )


class GeneratedReport(Base):
    """Historical archive of exported audit reports generated by the platform."""
    __tablename__ = "generated_reports"

    id: Mapped[int] = mapped_column(primary_key=True)
    reporting_period_id: Mapped[int] = mapped_column(
        ForeignKey("reporting_periods.id", ondelete="CASCADE"), nullable=False
    )
    
    report_title: Mapped[str] = mapped_column(String(255), nullable=False)
    report_type: Mapped[ReportType] = mapped_column(Enum(ReportType), nullable=False)
    export_format: Mapped[ReportFormat] = mapped_column(Enum(ReportFormat), nullable=False)
    mime_type: Mapped[str] = mapped_column(String(100), nullable=False)
    
    # Path where compiled artifact is stored
    storage_path: Mapped[str] = mapped_column(Text, nullable=False)
    file_size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    
    # Frozen calculation snapshot used to render this exact report
    computation_snapshot: Mapped[dict] = mapped_column(JSON, nullable=False)
    
    generated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False
    )

    reporting_period: Mapped["ReportingPeriod"] = relationship(back_populates="generated_reports")


# Performance Index
Index("ix_reporting_period_dates", ReportingPeriod.firm_id, ReportingPeriod.start_date, ReportingPeriod.end_date)
